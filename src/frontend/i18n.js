export function normalizeLang(code) {
  if (!code || typeof code !== 'string') return 'en';
  const short = code.toLowerCase().split(/[_-]/)[0];
  return dictionaries[short] ? short : 'en';
}

export function getStoredLanguage() {
  try {
    if (typeof window === 'undefined') return null;
    return normalizeLang(window.localStorage.getItem(STORAGE_KEY) || '');
  } catch {
    return null;
  }
}

export function storeLanguage(code) {
  try {
    if (typeof window === 'undefined') return;
    window.localStorage.setItem(STORAGE_KEY, normalizeLang(code));
  } catch {
    // ignore
  }
}

export function resolveInitialLanguage(defaultLang = 'en') {
  const stored = getStoredLanguage();
  if (stored && dictionaries[stored]) return stored;
  return normalizeLang(defaultLang);
}

export function isRtl(code) {
  const lang = LANGUAGES.find((l) => l.code === normalizeLang(code));
  return !!(lang && lang.rtl);
}

export function translate(lang, key, vars = {}) {
  const dict = dictionaries[normalizeLang(lang)] || dictionaries.en;
  let text = dict[key] ?? dictionaries.en[key] ?? key;
  Object.keys(vars).forEach((name) => {
    text = text.replace(new RegExp(`\\{${name}\\}`, 'g'), String(vars[name]));
  });
  return text;
}

export function nightsLabel(lang, nights, options, from, to) {
  const n = Number(nights) || 1;
  const o = Number(options) || 0;
  const pluralNights = n > 1;
  const pluralOptions = o !== 1;
  let key = 'nightsOneOption';
  if (pluralNights && pluralOptions) key = 'nightsOptionsPlural';
  else if (pluralNights && !pluralOptions) key = 'nightsOneOptionPlural';
  else if (!pluralNights && pluralOptions) key = 'nightsOptions';
  else key = 'nightsOneOption';
  return translate(lang, key, { nights: n, options: o, from, to });
}
